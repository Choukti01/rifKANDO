-- Private collaboration timeline for each service request. Delivery links are
-- validated as HTTPS by the API; no client work is sent through public media.

CREATE TABLE IF NOT EXISTS service_workroom_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_order_id BIGINT NOT NULL REFERENCES service_orders(id) ON DELETE CASCADE,
  author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  entry_type TEXT NOT NULL,
  body TEXT NOT NULL DEFAULT '',
  delivery_url TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT service_workroom_entries_type_check CHECK (entry_type IN ('message', 'delivery', 'revision'))
);

CREATE INDEX IF NOT EXISTS idx_service_workroom_entries_order_created
  ON service_workroom_entries(service_order_id, created_at ASC, id ASC);
