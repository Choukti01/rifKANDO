-- Services launch as a request-and-hire marketplace. No payment or payout
-- state is introduced here: a provider integration must be reviewed before
-- rifKANDO accepts or holds online funds.

CREATE TABLE IF NOT EXISTS service_provider_profiles (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  headline TEXT NOT NULL DEFAULT '',
  introduction TEXT NOT NULL DEFAULT '',
  experience_summary TEXT NOT NULL DEFAULT '',
  skills JSONB NOT NULL DEFAULT '[]'::jsonb,
  languages JSONB NOT NULL DEFAULT '[]'::jsonb,
  credentials JSONB NOT NULL DEFAULT '[]'::jsonb,
  availability TEXT NOT NULL DEFAULT 'available',
  response_time TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT service_provider_profiles_availability_check
    CHECK (availability IN ('available', 'limited', 'unavailable'))
);

ALTER TABLE service_orders
  ADD COLUMN IF NOT EXISTS package_id BIGINT REFERENCES service_packages(id),
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ADD COLUMN IF NOT EXISTS provider_note TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS buyer_note TEXT NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS service_order_status_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_order_id BIGINT NOT NULL REFERENCES service_orders(id) ON DELETE CASCADE,
  actor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  from_status TEXT,
  to_status TEXT NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS service_reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_order_id BIGINT NOT NULL UNIQUE REFERENCES service_orders(id) ON DELETE CASCADE,
  service_id BIGINT NOT NULL REFERENCES services(id) ON DELETE CASCADE,
  buyer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  provider_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_service_provider_profiles_availability
  ON service_provider_profiles(availability);
CREATE INDEX IF NOT EXISTS idx_service_orders_buyer_updated
  ON service_orders(buyer_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_service_orders_provider_updated
  ON service_orders(provider_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_service_order_status_history_order
  ON service_order_status_history(service_order_id, created_at ASC);
CREATE INDEX IF NOT EXISTS idx_service_reviews_service_created
  ON service_reviews(service_id, created_at DESC);
