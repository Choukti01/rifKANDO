-- Manual Attijari bank-transfer settlement for service work. Bank account
-- configuration is intentionally environment-only; no account number is
-- stored in this table or returned by public service endpoints.

CREATE TABLE IF NOT EXISTS service_payment_transfers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_order_id BIGINT NOT NULL UNIQUE REFERENCES service_orders(id) ON DELETE RESTRICT,
  buyer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  provider_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  amount_minor BIGINT NOT NULL CHECK (amount_minor > 0),
  commission_minor BIGINT NOT NULL CHECK (commission_minor >= 0),
  provider_payout_minor BIGINT NOT NULL CHECK (provider_payout_minor >= 0),
  transfer_reference TEXT,
  buyer_note TEXT NOT NULL DEFAULT '',
  payment_status TEXT NOT NULL DEFAULT 'awaiting_payment',
  submitted_at TIMESTAMPTZ,
  verified_at TIMESTAMPTZ,
  verified_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  verification_note TEXT NOT NULL DEFAULT '',
  payout_status TEXT NOT NULL DEFAULT 'not_due',
  payout_reference TEXT,
  payout_note TEXT NOT NULL DEFAULT '',
  paid_at TIMESTAMPTZ,
  paid_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT service_payment_status_check CHECK (payment_status IN ('awaiting_payment', 'submitted', 'verified', 'rejected', 'refunded')),
  CONSTRAINT service_payout_status_check CHECK (payout_status IN ('not_due', 'due', 'paid', 'withheld'))
);

CREATE INDEX IF NOT EXISTS idx_service_payment_transfers_status_created
  ON service_payment_transfers(payment_status, payout_status, created_at ASC);
CREATE INDEX IF NOT EXISTS idx_service_payment_transfers_provider
  ON service_payment_transfers(provider_id, created_at DESC);
