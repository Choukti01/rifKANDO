-- Buyer-owned saved searches power low-volume, in-app discovery alerts. They
-- never contain payment data or seller-private data and are deduplicated per
-- search/listing pair before a notification is issued.
CREATE TABLE saved_product_searches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  filters JSONB NOT NULL,
  filter_signature TEXT NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (user_id, filter_signature)
);

CREATE INDEX saved_product_searches_user_created_idx
  ON saved_product_searches (user_id, created_at DESC);

CREATE TABLE saved_product_search_notifications (
  saved_search_id BIGINT NOT NULL REFERENCES saved_product_searches(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (saved_search_id, product_id)
);
