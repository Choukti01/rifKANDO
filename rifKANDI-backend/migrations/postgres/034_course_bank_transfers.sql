-- Bank details remain in environment configuration, never in this table.
CREATE TABLE course_bank_transfers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_number TEXT NOT NULL UNIQUE,
  course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE RESTRICT,
  buyer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  instructor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  amount_minor BIGINT NOT NULL CHECK (amount_minor > 0),
  commission_minor BIGINT NOT NULL CHECK (commission_minor >= 0),
  instructor_payout_minor BIGINT NOT NULL CHECK (instructor_payout_minor >= 0),
  currency TEXT NOT NULL DEFAULT 'MAD' CHECK (currency = 'MAD'),
  payment_status TEXT NOT NULL DEFAULT 'awaiting_payment' CHECK (payment_status IN ('awaiting_payment','submitted','verified','rejected','refunded')),
  transfer_reference TEXT,
  verification_note TEXT NOT NULL DEFAULT '',
  verified_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  verified_at TIMESTAMPTZ,
  payout_status TEXT NOT NULL DEFAULT 'not_due' CHECK (payout_status IN ('not_due','due','paid','withheld')),
  payout_reference TEXT,
  paid_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  paid_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (course_id, buyer_id),
  CHECK (amount_minor = commission_minor + instructor_payout_minor)
);
CREATE INDEX idx_course_bank_transfers_queue ON course_bank_transfers(payment_status, payout_status, created_at);
