-- Redacted operational diagnostics. This is intentionally separate from the
-- immutable audit log because application errors may be grouped and retained
-- under a shorter operational policy.
CREATE TABLE application_error_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  source TEXT NOT NULL CHECK (source IN ('backend', 'frontend')),
  severity TEXT NOT NULL CHECK (severity IN ('error', 'warning')),
  fingerprint TEXT NOT NULL,
  error_name TEXT NOT NULL,
  message TEXT NOT NULL,
  route TEXT NOT NULL,
  method TEXT,
  status_code INTEGER,
  request_id TEXT,
  user_id BIGINT REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX idx_application_error_events_recent
  ON application_error_events(occurred_at DESC);

CREATE INDEX idx_application_error_events_fingerprint
  ON application_error_events(fingerprint, occurred_at DESC);
