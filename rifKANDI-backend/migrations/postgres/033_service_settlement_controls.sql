-- Private provider settlement details and a formal service-dispute hold.
-- These records are deliberately excluded from every public provider endpoint.

CREATE TABLE IF NOT EXISTS service_provider_payout_profiles (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  account_holder TEXT NOT NULL,
  payout_method TEXT NOT NULL DEFAULT 'bank_transfer',
  bank_name TEXT NOT NULL DEFAULT '',
  rib TEXT NOT NULL DEFAULT '',
  payout_phone TEXT NOT NULL DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT service_provider_payout_method_check
    CHECK (payout_method IN ('bank_transfer', 'cash_collection')),
  CONSTRAINT service_provider_payout_rib_check
    CHECK (payout_method <> 'bank_transfer' OR rib ~ '^[0-9]{20,34}$')
);

CREATE TABLE IF NOT EXISTS service_disputes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service_order_id BIGINT NOT NULL UNIQUE REFERENCES service_orders(id) ON DELETE RESTRICT,
  buyer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  provider_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  reason TEXT NOT NULL,
  description TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'open',
  resolution_note TEXT NOT NULL DEFAULT '',
  resolution_reference TEXT NOT NULL DEFAULT '',
  resolved_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  resolved_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT service_disputes_reason_check
    CHECK (reason IN ('not_delivered', 'not_as_agreed', 'quality_issue', 'communication', 'other')),
  CONSTRAINT service_disputes_status_check
    CHECK (status IN ('open', 'in_review', 'resolved_buyer', 'resolved_provider', 'closed'))
);

CREATE TABLE IF NOT EXISTS service_dispute_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dispute_id BIGINT NOT NULL REFERENCES service_disputes(id) ON DELETE CASCADE,
  actor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  event_type TEXT NOT NULL,
  body TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_service_disputes_status_updated
  ON service_disputes(status, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_service_disputes_participants
  ON service_disputes(buyer_id, provider_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_service_dispute_events_dispute_created
  ON service_dispute_events(dispute_id, created_at ASC, id ASC);
